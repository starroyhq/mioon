import React from 'react';

export type RecoveryStorageDetailsProps =
  | { domain: 'clip' | 'delivery' | 'shot-text' }
  | { domain: 'task-center'; durableOperationCount: number };

/** Disclosure only. Storage limits and retention follow the existing contracts;
 * opening this native disclosure does not read, restore, or submit anything. */
export default function RecoveryStorageDetails(props: RecoveryStorageDetailsProps) {
  if (props.domain === 'task-center') return <details className="helper muted" data-testid="recovery-task-storage-disclosure">
    <summary>保存范围与容量说明</summary>
    <p>{props.durableOperationCount} 类本地编辑请求由现有 SQLite 任务台账保留原编号与完整参数。最多保留 4096 个请求身份，已完成并关闭的记录也占容量；尚未提供归档或槽位清理，不会自动删除旧身份。达到上限会阻止新建此类任务，不表示磁盘已满，也不是整个数据库或 WAL 的大小上限。</p>
    <p>除下述专用入口外，既有画板/素材编辑及普通时间线渲染/预览的待确认参数仍依赖当前浏览器会话。完整镜头表单中的非文字或混合修改，以及生成提交仍沿用各自原有恢复规则。</p>
    <p>普通工作区中的例外是交付面板的成片导出（purpose=export）和镜头标题/提示词专用保存：它们另有持久原请求，需回到原交付面板或镜头面板明确恢复。任务中心不会汇总这些旁文件中的全部原请求。读取记录、打开面板或重新连接不会自动执行业务或调用模型；原请求恢复只使用保存的原编号与精确参数。</p>
    <ul>
      <li>片段属性草稿：累计最多 128 个项目/时间线/片段目标槽位。</li>
      <li>成片名称草稿与原导出请求：最多 128 个项目槽位。</li>
      <li>标题/提示词草稿与原文字请求：最多 128 个项目/镜头槽位。</li>
      <li>最近项目定位：仅保留 1 条位置记录，成功记住新项目会覆盖上一条。</li>
    </ul>
    <p>前三类清除草稿后仍保留版本记录并占用槽位，尚未提供槽位清理；容量限制不表示磁盘已满。以上四类旁文件均不包含在工作区离线备份中。恢复分支不启用这些旁文件，原有允许的手动编辑、保存和本机导出仍可使用。</p>
    <p>本地恢复记录是本机私有目录中的明文用户数据，未经保险库加密，不保存账号或认证配置；名称、提示词等自由文本仍可能包含隐私。放弃草稿或重置当前输入不会取消原请求，也不保证清除原请求已捕获的文本。最后未收到确认的输入可能丢失。</p>
  </details>;

  if (props.domain === 'clip') return <details className="export-preflight-scope" data-testid="clip-draft-disclosure">
    <summary>本地保存什么？</summary>
    <p>保存片段属性的原始输入、原时间线版本和素材来源，包括名称、轨道、时间、矩形、音量与淡入淡出。读取或恢复到属性表单不会保存到时间线，也不会调用模型；原业务请求仍由任务中心单独核对。</p>
    <p>草稿在本机私有目录中以明文保存，不保存账号或认证配置；片段名称等自由文本仍可能包含隐私。最后未收到确认的输入可能丢失。</p>
    <p>本工作区累计最多 128 个项目/时间线/片段目标槽位；清除草稿后保留的版本记录仍占位。尚未提供槽位清理，已有记录不会自动删除；容量限制不表示磁盘已满。</p>
    <p>放弃已保存草稿不会取消原业务请求或清除其记录。“放弃当前输入，保留草稿记录”只重置表单，不取消在途草稿写入；已保存或稍后写入的草稿可能再次出现。</p>
    <p>此草稿旁文件不包含在工作区离线备份中。恢复分支不读写本地片段草稿，原有允许的手动片段编辑与保存仍可使用。</p>
  </details>;

  if (props.domain === 'delivery') return <details className="export-preflight-scope" data-testid="delivery-draft-disclosure">
    <summary>本地保存什么？</summary>
    <p>名称草稿仅保存原始名称输入及原时间线版本，不保存可编辑的输出规格。恢复名称不会导出，也不会自动改用当前时间线版本。</p>
    <p>导出前会单独保存原请求编号与完整参数，包括本次输出规格和已有检查的摘要标识。打开面板、重新连接或读取记录均不会提交或重试导出。明确恢复原请求才会按原编号与精确参数核对或执行，不会改用当前名称或规格，也不会调用模型。</p>
    <p>本工作区最多保留 128 个项目槽位；清除名称后保留的版本记录与最新原导出请求仍占位。尚未提供槽位清理，已有记录不会自动删除；容量限制不表示磁盘已满。</p>
    <p>名称草稿与原导出请求在本机私有目录中以明文保存，不保存账号或认证配置；名称等自由文本仍可能包含隐私。放弃名称草稿或重置当前输入不会取消原导出请求，也不保证清除原请求已捕获的名称。最后未收到确认的输入可能丢失。</p>
    <p>此旁文件中的名称草稿与原导出请求均不包含在工作区离线备份中。恢复分支不读写这些记录，现有的明确确认本机导出流程仍可使用。</p>
  </details>;

  return <details className="export-preflight-scope" data-testid="shot-text-draft-disclosure">
    <summary>本地保存什么？</summary>
    <p>仅保存原始标题、提示词、原文字与保存版本，不保存参考图或生成参数。保存文字前会单独持久保存原请求编号与精确文字修改。</p>
    <p>打开面板、重新连接和读取记录都不会恢复文字或执行保存。恢复草稿只替换标题和提示词，其他输入保留。明确恢复原请求才会按原编号与原文字核对或执行，不会改用当前输入，也不会调用模型或生成镜头。</p>
    <p>本工作区最多保留 128 个项目/镜头槽位；清除草稿后保留的版本记录与最新原文字请求仍占位。尚未提供槽位清理，已有记录不会自动删除；还受旁文件载荷上限约束，容量限制不表示磁盘已满。</p>
    <p>文字草稿与原请求在本机私有目录中以明文保存，不保存账号或认证配置；标题、提示词等自由文本仍可能包含隐私。放弃文字草稿或重置当前输入不会取消原文字请求，也不保证清除原请求已捕获的文字。最后未收到确认的输入可能丢失。</p>
    <p>此旁文件中的文字草稿与原请求不包含在工作区备份中，包括离线备份。恢复分支不读写这些记录，现有镜头编辑与保存仍可使用。</p>
  </details>;
}
